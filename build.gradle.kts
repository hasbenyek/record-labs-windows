// Listen Together: official builds prove themselves to the Record Labs server with a
// key that is never committed. Put LISTEN_TOGETHER_KEY=<key> in local.properties
// (or set the LISTEN_TOGETHER_KEY environment variable). Without it the app still
// builds and runs; it just sends no key.
val listenTogetherKey: String = run {
    val properties = Properties()
    val file = rootProject.file("local.properties")
    if (file.exists()) file.inputStream().use(properties::load)
    (properties.getProperty("LISTEN_TOGETHER_KEY") ?: System.getenv("LISTEN_TOGETHER_KEY") ?: "").trim()
}

val generateListenTogetherKey by tasks.registering {
    val key = listenTogetherKey
    val outputDir = layout.buildDirectory.dir("generated/listenTogetherKey")
    inputs.property("key", key)
    outputs.dir(outputDir)
    doLast {
        // Stored masked so the key is not a plain string in the app's files.
        val bytes = key.toByteArray(Charsets.UTF_8)
        val mask = ByteArray(bytes.size).also { SecureRandom().nextBytes(it) }
        val masked = ByteArray(bytes.size) { (bytes[it].toInt() xor mask[it].toInt()).toByte() }
        fun ByteArray.literal() = joinToString(", ") { it.toString() }
        val file = outputDir.get().file("com/recordlabs/desktop/data/ListenTogetherBuildKey.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |package com.recordlabs.desktop.data
            |
            |// Generated by build.gradle.kts (generateListenTogetherKey). Do not commit.
            |internal object ListenTogetherBuildKey {
            |    private val a = byteArrayOf(${masked.literal()})
            |    private val b = byteArrayOf(${mask.literal()})
            |    val value: String get() = String(ByteArray(a.size) { (a[it].toInt() xor b[it].toInt()).toByte() }, Charsets.UTF_8)
            |}
            |""".trimMargin()
        )
    }
}

